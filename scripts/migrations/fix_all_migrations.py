def validate_migrations():
    """Validate that all migrations can be loaded correctly."""
    try:
        # Import the MigrationLoader to test if the migration graph can be built
        from django.db import connections
        from django.db.migrations.loader import MigrationLoader

        # Get the default database connection
        connection = connections["default"]

        # Try to build the migration graph
        loader = MigrationLoader(connection)
        print("Successfully built migration graph!")

        # Count migrations
        migration_count = sum(
            1 for node in loader.graph.nodes if node[0] != "__setting__"
        )
        print(f"Found {migration_count} migrations in the graph")

        # Check for any missing dependencies (DummyNodes)
        dummy_nodes = [
            node
            for node in loader.graph.node_map.values()
            if hasattr(loader.graph, "DummyNode")
            and isinstance(node, loader.graph.DummyNode)
        ]

        if dummy_nodes:
            print("\nWARNING: There are still missing migrations:")
            for node in dummy_nodes:
                print(f"  - Missing: {node.key}")
            return False

        return True
    except Exception as e:
        print(f"\nERROR: Failed to validate migrations: {str(e)}")
        return False


