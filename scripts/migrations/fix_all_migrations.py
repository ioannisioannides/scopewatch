#!/usr/bin/env python
"""
Fix All Migrations Script

This script comprehensively fixes all migration dependency issues by:
1. Creating any missing migration files
2. Ensuring all migration paths are consistent
3. Testing that the migration graph can be built successfully

Run this before running migrations or tests to ensure a consistent environment.

Usage:
    python fix_all_migrations.py
"""

import importlib
import os
import sys
from pathlib import Path

import django
from django.conf import settings

# Configure Django settings
os.environ.setdefault("DJANGO_SETTINGS_MODULE", "scopewatch.settings")
